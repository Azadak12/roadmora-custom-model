"""
Generates a synthetic, labeled training dataset for the RIASEC regression
model: (assessment answers) -> (6-dim RIASEC score vector).

Ground truth grounding: each row is generated by picking a REAL O*NET
occupation (from data/raw/onet/occupation_riasec.json, which has genuine
Dept. of Labor RIASEC scores), then sampling plausible assessment answers
for someone suited to that occupation — specific interest areas are drawn
from the REAL O*NET crosswalk (specific_interest_areas.json), weighted
toward whichever RIASEC types that occupation scores highest on. The
occupation's own real RIASEC vector becomes the training target.

This is still synthetic in the sense that no real user filled out this
particular assessment — but the label (RIASEC vector) and the interest
taxonomy are both real O*NET data, not invented. Document this precisely
in your report: the *supervision signal* is authoritative; the *sampling
of individual synthetic respondents* is not.

Run:
    cd ml && python3 scripts/generate_dataset.py
Output:
    ml/data/raw/synthetic_assessments.jsonl
"""

import json
import random
from collections import defaultdict
from pathlib import Path

from features import (
    EDUCATION_LEVELS, INDUSTRIES, JOB_ROLES, LANGUAGES, RIASEC_TYPES, SOFT_SKILLS,
    SPECIFIC_INTEREST_AREAS, STATUSES, TECHNICAL_SKILLS, _load,
)

random.seed(42)

RAW_DIR = Path(__file__).resolve().parent.parent / "data" / "raw"
OUTPUT_PATH = RAW_DIR / "synthetic_assessments.jsonl"
OCCUPATIONS_PATH = RAW_DIR / "onet" / "occupation_riasec.json"

N_PER_OCCUPATION = 150          # synthetic respondents generated per real occupation
INTEREST_NOISE_PROB = 0.35      # chance of an extra interest area unrelated to the occupation's RIASEC profile
INDUSTRY_RANDOM_PROB = 0.5
SKILL_RANDOM_PROB = 0.2         # lowered: technical skills are a cleaner RIASEC signal than O*NET's dated
SKILL_EMPTY_PROB = 0.15         # interest-area taxonomy for modern tech roles, so keep more of it un-diluted

# Loose, illustrative mapping from RIASEC type to technical-skill categories and
# industries — used only to add correlated (not deterministic) secondary signal.
SKILLS_BY_CATEGORY = _load("technical_skills")

RIASEC_TO_SKILL_CATEGORIES = {
    "Realistic": ["Engineering & Technical", "Mobile Development", "Other Technical"],
    "Investigative": ["Data Science & AI/ML", "Programming Languages", "Engineering & Technical"],
    "Artistic": ["Design & Media"],
    "Social": ["Business & Productivity Tools"],
    "Enterprising": ["Business & Productivity Tools"],
    "Conventional": ["Business & Productivity Tools", "Databases"],
}
RIASEC_TO_INDUSTRIES = {
    "Realistic": ["Manufacturing", "Automotive", "Agriculture", "Energy & Utilities", "Real Estate & Construction"],
    "Investigative": ["Technology / Software", "Healthcare & Pharmaceuticals", "Aerospace & Defense"],
    "Artistic": ["Media & Entertainment", "Marketing & Advertising"],
    "Social": ["Education", "Non-Profit / NGO", "Healthcare & Pharmaceuticals"],
    "Enterprising": ["Startups", "Consulting", "Finance & Banking", "E-commerce & Retail"],
    "Conventional": ["Finance & Banking", "Insurance", "Government / Public Sector"],
}

# Internships reuse the same RIASEC->industry pool (internships are just
# "which industry" one step earlier in a career). Job experience needs its
# own pool since it's role titles, not industries.
RIASEC_TO_JOB_ROLES = {
    "Realistic": ["Electrician/Technician", "Civil/Mechanical Engineer", "Warehouse/Logistics Staff", "Lab Technician"],
    "Investigative": ["Data Scientist", "Data Analyst", "Research Assistant", "Software Developer", "Lab Technician"],
    "Artistic": ["Graphic Designer", "UI/UX Designer", "Content Writer", "Video Editor"],
    "Social": ["Teacher/Tutor", "Nurse/Healthcare Worker", "Customer Service Representative", "HR Coordinator"],
    "Enterprising": ["Sales Representative", "Marketing Executive", "Entrepreneur/Founder", "Project Manager", "Operations Manager"],
    "Conventional": ["Accountant", "Financial Analyst", "Office Administrator", "IT Support Specialist", "Software Developer"],
}


def load_occupations():
    with open(OCCUPATIONS_PATH) as f:
        return json.load(f)


def build_riasec_to_interests():
    """Reverse index: RIASEC type -> list of specific interest area names."""
    idx = defaultdict(list)
    for area, riasec_list in SPECIFIC_INTEREST_AREAS.items():
        for r in riasec_list:
            idx[r].append(area)
    return idx


def top_riasec_types(riasec: dict, n=3):
    return [t for t, _ in sorted(riasec.items(), key=lambda kv: -kv[1])[:n]]


def sample_row(occupation: dict, riasec_to_interests: dict) -> dict:
    riasec = occupation["riasec"]
    dominant = top_riasec_types(riasec, n=3)
    all_types = RIASEC_TYPES

    # --- specific interest areas: weighted toward the occupation's dominant RIASEC types ---
    candidate_areas = []
    for t in dominant:
        candidate_areas.extend(riasec_to_interests.get(t, []))
    candidate_areas = list(dict.fromkeys(candidate_areas)) or list(SPECIFIC_INTEREST_AREAS.keys())
    n_interests = random.randint(2, min(5, len(candidate_areas)))
    interests = random.sample(candidate_areas, n_interests)
    if random.random() < INTEREST_NOISE_PROB:
        weak_type = random.choice([t for t in all_types if t not in dominant])
        weak_pool = riasec_to_interests.get(weak_type, [])
        if weak_pool:
            interests.append(random.choice(weak_pool))

    # --- technical skills: loosely correlated with dominant RIASEC types ---
    technical_skills = []
    if random.random() > SKILL_EMPTY_PROB:
        if random.random() < SKILL_RANDOM_PROB:
            technical_skills = random.sample(TECHNICAL_SKILLS, random.randint(1, 4))
        else:
            pool = []
            for t in dominant:
                for cat in RIASEC_TO_SKILL_CATEGORIES.get(t, []):
                    pool.extend(SKILLS_BY_CATEGORY.get(cat, []))
            pool = list(dict.fromkeys(pool))
            if pool:
                technical_skills = random.sample(pool, min(random.randint(2, 6), len(pool)))

    # --- soft skills: weakly informative ---
    soft_skills = random.sample(SOFT_SKILLS, random.randint(2, 5))

    # --- languages: independent of career ---
    languages = ["English"]
    if random.random() < 0.7:
        languages.append(random.choice([l for l in LANGUAGES if l != "English"]))
    languages = list(dict.fromkeys(languages))

    # --- preferred industries: loosely correlated, often random ---
    if random.random() < INDUSTRY_RANDOM_PROB:
        preferred_industries = random.sample(INDUSTRIES, random.randint(1, 3))
    else:
        pool = []
        for t in dominant:
            pool.extend(RIASEC_TO_INDUSTRIES.get(t, []))
        pool = [p for p in dict.fromkeys(pool) if p in INDUSTRIES] or INDUSTRIES
        preferred_industries = random.sample(pool, min(len(pool), random.randint(1, 3)))

    # --- internships: same RIASEC->industry pool, independent random draw ---
    if random.random() < INDUSTRY_RANDOM_PROB:
        internships = random.sample(INDUSTRIES, random.randint(0, 2))
    else:
        pool = []
        for t in dominant:
            pool.extend(RIASEC_TO_INDUSTRIES.get(t, []))
        pool = [p for p in dict.fromkeys(pool) if p in INDUSTRIES] or INDUSTRIES
        internships = random.sample(pool, min(len(pool), random.randint(0, 2)))

    # --- job experience: correlated with dominant RIASEC types, often empty (many respondents have none) ---
    job_experience = []
    if random.random() > 0.3:
        if random.random() < 0.3:
            job_experience = random.sample(JOB_ROLES, random.randint(1, 2))
        else:
            pool = []
            for t in dominant:
                pool.extend(RIASEC_TO_JOB_ROLES.get(t, []))
            pool = list(dict.fromkeys(pool))
            if pool:
                job_experience = random.sample(pool, min(random.randint(1, 2), len(pool)))

    return {
        "education": random.choices(EDUCATION_LEVELS, weights=[10, 10, 50, 20, 5, 5])[0],
        "status": random.choices(STATUSES, weights=[45, 20, 20, 10, 5])[0],
        "technicalSkills": technical_skills,
        "softSkills": soft_skills,
        "languages": languages,
        "careerInterests": interests,
        "preferredIndustries": preferred_industries,
        "internships": internships,
        "jobExperience": job_experience,
        "riasec_label": riasec,
        "occupation_title": occupation["title"],
        "onet_soc_code": occupation["onet_soc_code"],
    }


def main():
    occupations = load_occupations()
    riasec_to_interests = build_riasec_to_interests()

    rows = []
    for occ in occupations:
        for _ in range(N_PER_OCCUPATION):
            rows.append(sample_row(occ, riasec_to_interests))
    random.shuffle(rows)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_PATH, "w") as f:
        for row in rows:
            f.write(json.dumps(row) + "\n")

    print(f"Wrote {len(rows)} synthetic rows to {OUTPUT_PATH}")
    print(f"  {N_PER_OCCUPATION} rows per occupation x {len(occupations)} real O*NET occupations")


if __name__ == "__main__":
    main()
